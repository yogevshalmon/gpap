#!/usr/bin/env python3
"""WAVE-vs-SCALAR kernel tables from an eval/profiling/kernel_ab.py JSON.

The exclusion rules live HERE, once, same as the paper's other generators:
  * vacuous-pin and zero-search instances are dropped (no propagation work -> the kernel is not
    what is being measured);
  * a cell where either arm produced nothing in the budget has no finite ratio and is counted
    in its own column, never in a geomean;
  * `--min-models` (default 100) drops cells whose rates rest on a handful of models — their
    ratio is draw noise (docs/BENCHMARKING.md §3); the all-rows geomean is printed beside it
    so the reader can see the cut costs nothing.

    eval/profiling/kernel_ab_tables.py .experiments/kernel_ab/kernel_ab.json \\
        --out-md $GPAP_RESULTS/paper/KERNEL_AB.md

The output is NOT committed in the repository: the last such table was removed rather than left
stale when the shuffle schedule moved the crossover, and a generated file belongs beside the
campaign that produced it until the paper cites it. It emits no LaTeX, for the same reason the
paper's own generator stopped: a paper typesets its own tables, so a generated `.tex` nobody
includes is a second rendering of the same numbers with nothing holding the two in step.
"""
import argparse
import json
import math
import sys
from collections import OrderedDict

M_BINS = OrderedDict([("M < 2k", (0, 2048)), ("2k–20k", (2048, 20_000)),
                      ("20k–100k", (20_000, 100_000)), ("> 100k", (100_000, 10**12))])
FAMILY_LABEL = {"seq": "ITC'99 + ISCAS-89 sequential (T=25)", "comb": "ISCAS-85 combinational",
                "epfl": "EPFL combinational", "hwmcc": "HWMCC'17 property (T=25)",
                "sk": "Sketch / sk_ projected CNF"}


def gm(xs):
    return math.exp(sum(math.log(x) for x in xs) / len(xs))


def comparable(rows, min_models):
    out = []
    for r in rows:
        rt = r.get("ratio")
        if rt in (None, 0.0, float("inf")) or r.get("vacuous") or r.get("zero_search"):
            continue
        if r["scalar"]["models"] < min_models or r["wave"]["models"] < min_models:
            continue
        out.append(r)
    return out


def stats(rs):
    if not rs:
        return None
    rat = sorted(r["ratio"] for r in rs)
    return {"n": len(rs), "geomean": gm(rat), "median": rat[len(rat) // 2],
            "min": rat[0], "max": rat[-1], "wins": sum(1 for x in rat if x > 1)}


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("json")
    ap.add_argument("--min-models", type=int, default=100)
    ap.add_argument("--out-md", default=None)
    args = ap.parse_args()
    d = json.load(open(args.json))
    rows, gpu = d["rows"], d.get("gpu", {})
    a = d.get("args", {})
    head = comparable(rows, args.min_models)
    allrows = comparable(rows, 0)
    n_vac = sum(1 for r in rows if r.get("vacuous"))
    n_zs = sum(1 for r in rows if r.get("zero_search") and not r.get("vacuous"))
    n_none = sum(1 for r in rows if r.get("ratio") is None and not r.get("error"))
    n_cut = len(allrows) - len(head)
    val_ok = sum(1 for r in rows if (r.get("validation") or {}).get("passed"))
    H = stats(head)
    A = stats(allrows)
    agree = sum(1 for r in head if (r["ratio"] > 1) == (r["auto_pick"] == "wave"))

    md = []
    md.append(f"# WAVE vs SCALAR propagate kernel — {gpu.get('name', '?')}")
    md.append("")
    md.append(f"Generated by `eval/profiling/kernel_ab_tables.py` from `{args.json}` "
              f"(eval/profiling/kernel_ab.py: kernel forced per arm, pinned `{a.get('portfolio')}` config, "
              f"mining off, {a.get('time_limit')} s wall × {a.get('reps')} alternated reps, "
              f"best-of per arm; validation = identical model counts at pinned K, "
              f"{val_ok}/{len(rows)} cells passed).")
    md.append("")
    md.append(f"**Headline: WAVE / SCALAR = {H['geomean']:.2f}× geomean (median {H['median']:.2f}×, "
              f"WAVE faster on {H['wins']}/{H['n']}) over {H['n']} cells** "
              f"(both arms ≥ {args.min_models} models; all {A['n']} comparable cells: {A['geomean']:.2f}×, "
              f"range {A['min']:.2f}–{A['max']:.2f}). "
              f"Excluded: {n_vac} vacuous-pin, {n_zs} zero-search, {n_none} where neither kernel "
              f"produced a model in the budget, {n_cut} below the model floor.")
    md.append("")
    md.append("## By clause count")
    md.append("")
    md.append("| clauses M | cells | WAVE/SCALAR geomean | median | min–max | WAVE faster |")
    md.append("|---|---:|---:|---:|---:|---:|")
    for name, (lo, hi) in M_BINS.items():
        s = stats([r for r in head if lo <= r["M"] < hi])
        if s:
            md.append(f"| {name} | {s['n']} | **{s['geomean']:.2f}×** | {s['median']:.2f}× | "
                      f"{s['min']:.2f}–{s['max']:.2f} | {s['wins']}/{s['n']} |")
    md.append("")
    md.append("## By family")
    md.append("")
    md.append("| family | cells | geomean | WAVE faster | M range |")
    md.append("|---|---:|---:|---:|---:|")
    for fam, label in FAMILY_LABEL.items():
        b = [r for r in head if r["family"] == fam]
        s = stats(b)
        if s:
            mr = f"{min(r['M'] for r in b):,}–{max(r['M'] for r in b):,}"
            md.append(f"| {label} | {s['n']} | {s['geomean']:.2f}× | {s['wins']}/{s['n']} | {mr} |")
    md.append("")
    md.append("## By encoder")
    md.append("")
    md.append("| encoder | cells | geomean | WAVE faster |")
    md.append("|---|---:|---:|---:|")
    for enc in ("tseitin", "abc:fast", "cnf"):
        s = stats([r for r in head if r["encoder"] == enc])
        if s:
            md.append(f"| {enc} | {s['n']} | {s['geomean']:.2f}× | {s['wins']}/{s['n']} |")
    md.append("")
    dis = [r for r in head if (r["ratio"] > 1) != (r["auto_pick"] == "wave")]
    if dis:
        worst = max(dis, key=lambda r: abs(math.log(r["ratio"])))
        cost = worst["ratio"] if worst["auto_pick"] == "wave" else 1 / worst["ratio"]
        md.append(f"**Dispatch rule** (`wave` iff M ≥ 2048): picked the faster kernel on "
                  f"{agree}/{H['n']} cells. The {len(dis)} disagreements all lie at "
                  f"M = {min(r['M'] for r in dis):,}–{max(r['M'] for r in dis):,}; the costliest "
                  f"mis-pick ({worst['family']}/{worst['instance']}/{worst['encoder']}) runs at "
                  f"{cost:.2f}× of the faster kernel's rate — a mis-pick costs at most "
                  f"{(1 - cost) * 100:.0f}% on these cells (table below).")
    else:
        md.append(f"**Dispatch rule** (`wave` iff M ≥ 2048): picked the faster kernel on "
                  f"{agree}/{H['n']} cells.")
    md.append("")
    md.append("| cell | M | WAVE/SCALAR | rule picked |")
    md.append("|---|---:|---:|---|")
    for r in sorted(head, key=lambda r: r["M"]):
        if (r["ratio"] > 1) != (r["auto_pick"] == "wave"):
            md.append(f"| {r['family']}/{r['instance']}/{r['encoder']} | {r['M']:,} | "
                      f"{r['ratio']:.2f}× | {r['auto_pick']} |")
    md.append("")
    md.append("## Caveats (state in the text)")
    md.append("")
    md.append("* The IMPLICATION counters of the two kernels differ by ~0.6% on conflicted rows "
              "(propagation order decides which clause empties first); models and decisions agree "
              "exactly — the validation phase gates on models.")
    md.append("* Rates on low-success instances are draw-noisy (±40%); the model floor removes the "
              "cells whose ratio rests on a handful of models and moves the geomean by "
              f"{abs(A['geomean'] - H['geomean']):.2f}.")
    md.append("* Mining is OFF in this A/B (it is wall-budgeted, so a faster kernel would mine more "
              "and the arms would run different formulas); the shipped sampler mines by default, "
              "so absolute rates here are not the headline rates.")
    text = "\n".join(md) + "\n"

    print(text)
    if args.out_md:
        open(args.out_md, "w").write(text)
        print(f"wrote {args.out_md}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
